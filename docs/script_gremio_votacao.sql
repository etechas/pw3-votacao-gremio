Create DATABASE GremioVotacao;

USE GremioVotacao;

CREATE TABLE TBL_CANDIDATO (
	ID_CANDIDATO BIGINT  IDENTITY(1, 1) NOT NULL,
	TX_NOME VARCHAR(255) NULL,
	TP_CATEGORIA VARCHAR(50) NULL,
	NR_QUANTIDADEVOTOS INT NULL,
	CHK_ELEITO VARCHAR(10)
	CONSTRAINT PK_TBL_CANDIDATO PRIMARY KEY (ID_CANDIDATO)
);

